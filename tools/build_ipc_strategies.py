#!/usr/bin/env python3
"""Build audited, Python 3.6 compatible GBK strategies without runtime source reads."""
import argparse
import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
COMMON = ('transport/pipe/wire', 'transport/pipe/winpipe', 'qmt/executor')
ROLE = {'feed': ('feed/qmt_api',),
        'order': ('order/common', 'order/qmt', 'order/api_contracts', 'order/query')}
ALLOWED = {'collections', 'time', 'uuid', 'threading', 'ctypes', 'os', 'json',
           'struct', 'datetime', 'math', 'copy', 'hashlib', 're', 'decimal'}
BANNED_CALLS = {'open', '__import__', 'eval', 'exec', 'compile', 'input'}
BANNED_ATTRS = {'read_text', 'write_text', 'read_bytes', 'write_bytes', 'open',
                'connect', 'urlopen', 'socket', 'FileHandler', 'basicConfig'}


def audit(source, filename):
    tree = ast.parse(source, filename=filename, feature_version=(3, 6))
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            names = [alias.name.split('.')[0] for alias in node.names]
        elif isinstance(node, ast.ImportFrom) and not node.level:
            names = [(node.module or '').split('.')[0]]
        else:
            names = []
        if set(names) - ALLOWED:
            raise ValueError('unsafe import in {0}: {1}'.format(filename, names))
        if isinstance(node, ast.Call):
            fun = node.func
            if ((isinstance(fun, ast.Name) and fun.id in BANNED_CALLS) or
                    (isinstance(fun, ast.Attribute) and fun.attr in BANNED_ATTRS)):
                raise ValueError('unsafe call in {0}:{1}'.format(filename, node.lineno))
        if isinstance(node, ast.Attribute) and isinstance(node.value, ast.Name):
            if node.value.id == 'os' and node.attr != 'name':
                raise ValueError('unsafe os access in ' + filename)
    return tree


def render(role):
    prefix = '_qmt_ipc_' + role
    sources = []
    for name in COMMON + ROLE[role] + ('qmt/entrypoint',):
        path = ROOT / 'service' / 'ipc_bridge' / (name + '.py')
        source = path.read_text(encoding='utf-8-sig')
        audit(source, str(path))
        sources.append((prefix + '.' + name.replace('/', '.'), source))
    # Every module is compiled from embedded text, never loaded from application files.
    content = '''# -*- coding: gbk -*-
# Generated by tools/build_ipc_strategies.py; edit source modules instead.
# Parameters: bridge_id="default", account_id="66027616", pipe_name optional,
# schedule_interval_ms=10, schedule_budget_ms=50. Logs are console only.
import sys as _ipc_sys
import types as _ipc_types
_IPC_SOURCES = %r
for _ipc_name, _ipc_source in _IPC_SOURCES:
    _ipc_parts = _ipc_name.split('.')
    for _ipc_i in range(1, len(_ipc_parts)):
        _ipc_parent = '.'.join(_ipc_parts[:_ipc_i])
        if _ipc_parent not in _ipc_sys.modules:
            _ipc_package = _ipc_types.ModuleType(_ipc_parent)
            _ipc_package.__path__ = []
            _ipc_sys.modules[_ipc_parent] = _ipc_package
    _ipc_module = _ipc_types.ModuleType(_ipc_name)
    _ipc_module.__package__ = _ipc_name.rsplit('.', 1)[0]
    _ipc_sys.modules[_ipc_name] = _ipc_module
    exec(compile(_ipc_source, '<' + _ipc_name + '>', 'exec'), _ipc_module.__dict__)
_ipc_entry = _ipc_sys.modules[%r]
def init(ContextInfo):
    _ipc_entry.start(ContextInfo, globals(), %r)
process_ipc_requests = _ipc_entry.process_ipc_requests
stop = _ipc_entry.stop
handlebar = _ipc_entry.handlebar
order_callback = _ipc_entry.order_callback
deal_callback = _ipc_entry.deal_callback
task_callback = _ipc_entry.task_callback
orderError_callback = _ipc_entry.orderError_callback
account_callback = _ipc_entry.account_callback
''' % (sources, prefix + '.qmt.entrypoint', role)
    ast.parse(content, feature_version=(3, 6))
    return content.encode('gbk')


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args(argv)
    stale = False
    for role in ('feed', 'order'):
        output = ROOT / 'strategies' / ('ipc_' + role + '.py')
        expected = render(role)
        same = output.is_file() and output.read_bytes() == expected
        if args.check:
            stale = stale or not same
            print('{0}: {1}'.format(output.name, 'current' if same else 'stale'))
        elif not same:
            output.write_bytes(expected)
            print('written ' + output.name)
    return int(stale)


if __name__ == '__main__':
    raise SystemExit(main())
